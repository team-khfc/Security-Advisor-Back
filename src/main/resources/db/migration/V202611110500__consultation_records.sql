CREATE TABLE consultation_records (
 consultation_record_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 security_request_id BIGINT NOT NULL REFERENCES security_requests(security_request_id),
 kind VARCHAR(30) NOT NULL,
 actor_name VARCHAR(200) NOT NULL,
 actor_role VARCHAR(30) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL,
 payload TEXT NOT NULL
);
CREATE INDEX idx_consultation_records_request ON consultation_records(security_request_id, consultation_record_id);
