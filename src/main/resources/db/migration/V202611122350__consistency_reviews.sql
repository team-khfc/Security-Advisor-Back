CREATE TABLE consistency_reviews (
    consistency_review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    security_request_id BIGINT NOT NULL REFERENCES security_requests(security_request_id),
    result TEXT NOT NULL,
    decisions TEXT NOT NULL DEFAULT '[]',
    revision BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX consistency_reviews_request_idx ON consistency_reviews(security_request_id, consistency_review_id DESC);
