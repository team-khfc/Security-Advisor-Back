-- 신청자 인터뷰의 제안·질문 기록. 기존 업무 데이터는 변경하지 않는다.
-- 복구 시 새 기능의 사용을 중지하면 기존 신청·답변은 그대로 이용할 수 있다.
CREATE TABLE interview_turns (
    interview_turn_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_case_id BIGINT NOT NULL REFERENCES business_cases(business_case_id),
    applicant_username VARCHAR(50) NOT NULL REFERENCES members(username),
    field_key VARCHAR(100) NOT NULL,
    mode VARCHAR(20) NOT NULL CHECK (mode IN ('SUGGEST', 'ASK')),
    question TEXT NOT NULL,
    reply TEXT NOT NULL,
    proposed_value TEXT,
    evidence_refs JSONB NOT NULL,
    context_fingerprint VARCHAR(64) NOT NULL,
    based_revision BIGINT NOT NULL,
    answer_revision BIGINT,
    model_reference VARCHAR(200),
    flagged BOOLEAN NOT NULL DEFAULT FALSE,
    applied BOOLEAN NOT NULL DEFAULT FALSE,
    revision BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_interview_turns_case_user ON interview_turns (business_case_id, applicant_username, interview_turn_id DESC);
